"""Word levels of a target pack for the functions (docs/07-ai-tutor.md §4.3).

`tutor/gap_suggest` checks that the simple English it returns stays within
the learner's level plus one. The functions do not have the pack, so this
step writes the levels of the built pack's lexicon (`kind = 'lemma'`) and
the forms of those lemmas into a TypeScript module beside them:
`supabase/functions/_shared/levels/<l2>.ts`. Run it after every build of the
target pack; the module names the pack it came from.
"""

from __future__ import annotations

import json
import sqlite3
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

LEVELS_DIR = Path("supabase") / "functions" / "_shared" / "levels"
LEVEL_CODES = ("A1", "A2", "B1", "B2", "C1", "C2")

ATTRIBUTION = (
    "// Levels: CEFR-J Wordlist 1.5 (Tono Laboratory, TUFS) and Octanove Vocabulary\n"
    "// Profile C1/C2 (CC BY-SA 4.0), as in the pack's LICENSES.md."
)


@dataclass(frozen=True)
class PackLevels:
    """The lexicon of a target pack: lemma → level, form → its lemmas."""

    pack: str
    l2: str
    levels: dict[str, str]
    forms: dict[str, frozenset[str]]


@dataclass(frozen=True)
class LevelsReport:
    pack: str
    lemmas: int
    forms: int
    path: Path


def read_levels(pack_file: Path) -> PackLevels:
    """The levels of the lexicon in the built pack at [pack_file]."""
    with sqlite3.connect(f"file:{pack_file.as_posix()}?mode=ro", uri=True) as db:
        row = db.execute("SELECT value FROM pack_meta WHERE key = 'manifest'").fetchone()
        if row is None:
            raise ValueError(f"{pack_file}: no manifest")
        manifest = json.loads(row[0])
        if manifest.get("kind") != "target":
            raise ValueError(f"{pack_file}: not a target pack")
        levels: dict[str, str] = {}
        for lemmas, level in db.execute(
            "SELECT lemmas, level FROM content_items WHERE kind = 'lemma'"
        ):
            if level not in LEVEL_CODES:
                continue
            for lemma in json.loads(lemmas):
                key = lemma.lower()
                known = levels.get(key)
                # A lemma listed twice keeps its lower level.
                if known is None or LEVEL_CODES.index(level) < LEVEL_CODES.index(known):
                    levels[key] = level
        forms: dict[str, set[str]] = defaultdict(set)
        for form, lemma in db.execute("SELECT form, lemma FROM content_forms"):
            form_key, lemma_key = form.lower(), lemma.lower()
            if form_key != lemma_key and lemma_key in levels:
                forms[form_key].add(lemma_key)
    return PackLevels(
        pack=manifest["id"],
        l2=manifest["l2"],
        levels=levels,
        forms={form: frozenset(lemmas) for form, lemmas in forms.items()},
    )


def render(levels: PackLevels) -> str:
    """The TypeScript module of [levels]; the same input gives the same text."""
    name = f"{levels.l2}Levels"
    by_level: dict[str, list[str]] = {code: [] for code in LEVEL_CODES}
    for lemma, level in levels.levels.items():
        by_level[level].append(lemma)
    lemma_lines = [
        f"    {code}: {json.dumps(' '.join(sorted(words)), ensure_ascii=False)},"
        for code, words in by_level.items()
        if words
    ]
    pairs = "|".join(
        f"{form} {'/'.join(sorted(lemmas))}" for form, lemmas in sorted(levels.forms.items())
    )
    return "\n".join(
        [
            "// deno-fmt-ignore-file",
            f"// Generated by `dilbaz-content levels-module` from {levels.pack}; do not edit.",
            ATTRIBUTION,
            'import type { LevelData } from "./levels.ts";',
            "",
            f"export const {name}: LevelData = {{",
            f"  pack: {json.dumps(levels.pack)},",
            "  lemmas: {",
            *lemma_lines,
            "  },",
            f"  forms: {json.dumps(pairs, ensure_ascii=False)},",
            "};",
            "",
        ]
    )


def run_levels_module(root: Path, l2: str = "en") -> LevelsReport:
    """Writes the module of the built `<l2>@<version>` pack under [root]."""
    built = sorted((root / "build").glob(f"{l2}@*.sqlite"))
    if not built:
        raise FileNotFoundError(f"no built {l2} pack in {root / 'build'}; run build first")
    levels = read_levels(built[-1])
    out = root.parent / LEVELS_DIR / f"{l2}.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(levels), encoding="utf-8", newline="\n")
    return LevelsReport(
        pack=levels.pack,
        lemmas=len(levels.levels),
        forms=len(levels.forms),
        path=out,
    )
