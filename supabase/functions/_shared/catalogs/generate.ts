/**
 * Writes the catalogs of the pair packs as TypeScript modules.
 *
 *   deno run -A _shared/catalogs/generate.ts
 *
 * Run from `supabase/functions` after a pair pack's error catalog or rule
 * notes change; `catalog_test.ts` fails until then.
 */
import { dirname, fromFileUrl, join } from "@std/path";
import type { Catalog, ErrorTag } from "./catalog.ts";

const here = dirname(fromFileUrl(import.meta.url));
const packsDir = join(here, "..", "..", "..", "..", "content", "packs");

/** The pairs whose catalogs the functions carry. */
export const pairs = ["tr-en"] as const;

function lines(text: string): Record<string, unknown>[] {
  return text.split("\n").filter((line) => line.trim() !== "").map((line) =>
    JSON.parse(line)
  );
}

/** The catalog of [pair], read from its pack sources. */
export async function readCatalog(pair: string): Promise<Catalog> {
  const dir = join(packsDir, pair);
  const manifest = await Deno.readTextFile(join(dir, "manifest.yaml"));
  const pack = manifest.match(/^id:\s*(\S+)/m)?.[1];
  if (!pack) throw new Error(`${pair}: manifest has no id`);
  const tags = lines(await Deno.readTextFile(join(dir, "error_tags.jsonl")));
  const notes = lines(await Deno.readTextFile(join(dir, "rule_notes.jsonl")));
  return {
    pack,
    errorTags: tags.map((tag): ErrorTag => ({
      code: tag.code as string,
      category: tag.category as ErrorTag["category"],
      description: tag.description as string,
      example: (tag.examples as string[])[0],
    })),
    ruleNotes: Object.fromEntries(
      notes.map((note) => [note.code as string, note.note as string]),
    ),
  };
}

/** Module name of [pair]'s catalog: `tr-en` → `tr_en`. */
export const moduleName = (pair: string) => pair.replace("-", "_");

export function render(pair: string, catalog: Catalog): string {
  const name = `${
    moduleName(pair).replace(/_(\w)/, (_, c) => c.toUpperCase())
  }Catalog`;
  return [
    "// deno-fmt-ignore-file",
    `// Generated by generate.ts from content/packs/${pair}; do not edit.`,
    'import type { Catalog } from "./catalog.ts";',
    "",
    `export const ${name}: Catalog = ${JSON.stringify(catalog, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  for (const pair of pairs) {
    const path = join(here, `${moduleName(pair)}.ts`);
    await Deno.writeTextFile(path, render(pair, await readCatalog(pair)));
    console.log(`wrote ${path}`);
  }
}
