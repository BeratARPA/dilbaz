"""The Dilbaz icon, drawn once and written out for every platform.

A speech bubble holding a sound wave: speaking comes first (I-05). Teal is
the app's seed colour, the middle bar the warm accent.

    uv run app/assets/icon/make_icons.py

Writes the SVG sources next to this file, then the Android launcher icons
(adaptive with a themed monochrome layer, and the old square ones), the
notification icon, the Windows .ico and the web icons. Run it again after
changing the drawing; the outputs are committed.
"""

from io import BytesIO
from pathlib import Path

import resvg_py
from PIL import Image, ImageDraw

HERE = Path(__file__).parent
APP = HERE.parent.parent
RES = APP / "android" / "app" / "src" / "main" / "res"

TEAL = "#1F7A74"
TEAL_LIGHT = "#25918A"
TEAL_DARK = "#155C57"
CREAM = "#FFF8EC"
AMBER = "#F2A93B"

# The glyph on a 1024 canvas: the bubble's body, its tail, the wave.
BODY = (232, 262, 560, 430, 150)
TAIL = "M 332.8 690 L 265.6 821 L 467.2 690 Z"
BARS = [(372, 120), (447, 220), (522, 300), (597, 190), (672, 110)]
# The middle of the glyph, tail included: placed on the canvas's centre.
GLYPH_CENTRE = (512, 541)


def glyph(bubble: str, wave: str, accent: str) -> str:
    x, y, w, h, r = BODY
    bars = "".join(
        f'<rect x="{bx - 24}" y="{477 - bh / 2}" width="48" height="{bh}" '
        f'rx="24" fill="{accent if i == 2 else wave}"/>'
        for i, (bx, bh) in enumerate(BARS)
    )
    return (
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{bubble}"/>'
        f'<path d="{TAIL}" fill="{bubble}" stroke="{bubble}" stroke-width="6" '
        f'stroke-linejoin="round"/>{bars}'
    )


def placed(content: str, scale: float) -> str:
    cx, cy = GLYPH_CENTRE
    return (
        f'<g transform="translate(512 512) scale({scale}) '
        f'translate({-cx} {-cy})">{content}</g>'
    )


BACKGROUND = f"""<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
<stop offset="0" stop-color="{TEAL_LIGHT}"/><stop offset="1" stop-color="{TEAL_DARK}"/>
</linearGradient></defs><rect width="1024" height="1024" fill="url(#bg)"/>"""


def svg(body: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">{body}</svg>'
    )


# The whole icon, full bleed: the glyph fills about half of it.
FULL = svg(BACKGROUND + placed(glyph(CREAM, TEAL, AMBER), 1.0))
# Adaptive foreground: a 108 dp canvas of which ~72 dp shows; the glyph is
# made smaller so that it reads as large as on the square icon.
FOREGROUND = svg(placed(glyph(CREAM, TEAL, AMBER), 0.68))
# One colour, the wave cut out of the bubble: themed icons, notifications.
SILHOUETTE = (
    '<defs><mask id="cut"><rect width="1024" height="1024" fill="white"/>'
    + "".join(
        f'<rect x="{bx - 24}" y="{477 - bh / 2}" width="48" height="{bh}" rx="24" fill="black"/>'
        for bx, bh in BARS
    )
    + "</mask></defs>"
)


def mono(scale: float) -> str:
    x, y, w, h, r = BODY
    shape = (
        f'<g mask="url(#cut)"><rect x="{x}" y="{y}" width="{w}" height="{h}" '
        f'rx="{r}" fill="white"/><path d="{TAIL}" fill="white" stroke="white" '
        f'stroke-width="6" stroke-linejoin="round"/></g>'
    )
    return svg(SILHOUETTE + placed(shape, scale))


MONOCHROME = mono(0.68)
NOTIFICATION = mono(1.4)


def render(source: str, size: int) -> Image.Image:
    png = resvg_py.svg_to_bytes(svg_string=source, width=size, height=size)
    return Image.open(BytesIO(bytes(png))).convert("RGBA")


def rounded(img: Image.Image, radius: float = 0.22) -> Image.Image:
    size = img.size[0]
    mask = Image.new("L", (size * 4, size * 4), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (0, 0, size * 4 - 1, size * 4 - 1), radius=size * 4 * radius, fill=255
    )
    out = Image.new("RGBA", img.size, (0, 0, 0, 0))
    out.paste(img, (0, 0), mask.resize(img.size, Image.LANCZOS))
    return out


def save(img: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)


DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets/icon/make_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
"""

ADAPTIVE_BACKGROUND = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets/icon/make_icons.py -->
<shape xmlns:android="http://schemas.android.com/apk/res/android">
    <gradient
        android:angle="315"
        android:endColor="{TEAL_DARK}"
        android:startColor="{TEAL_LIGHT}"
        android:type="linear" />
</shape>
"""


def main() -> None:
    for name, source in {
        "dilbaz_icon.svg": FULL,
        "dilbaz_foreground.svg": FOREGROUND,
        "dilbaz_monochrome.svg": MONOCHROME,
    }.items():
        (HERE / name).write_text(source + "\n", encoding="utf-8", newline="\n")

    big = render(FULL, 1024)
    save(rounded(big), HERE / "dilbaz_icon.png")

    for density, factor in DENSITIES.items():
        folder = RES / f"mipmap-{density}"
        save(rounded(render(FULL, round(48 * factor))), folder / "ic_launcher.png")
        layer = round(108 * factor)
        save(render(FOREGROUND, layer), folder / "ic_launcher_foreground.png")
        save(render(MONOCHROME, layer), folder / "ic_launcher_monochrome.png")
        save(
            render(NOTIFICATION, round(24 * factor)),
            RES / f"drawable-{density}" / "ic_notification.png",
        )
    (RES / "mipmap-anydpi-v26").mkdir(exist_ok=True)
    (RES / "mipmap-anydpi-v26" / "ic_launcher.xml").write_text(
        ADAPTIVE, encoding="utf-8", newline="\n"
    )
    (RES / "drawable" / "ic_launcher_background.xml").write_text(
        ADAPTIVE_BACKGROUND, encoding="utf-8", newline="\n"
    )

    web = APP / "web"
    save(rounded(render(FULL, 192)), web / "icons" / "Icon-192.png")
    save(rounded(render(FULL, 512)), web / "icons" / "Icon-512.png")
    # Maskable: full bleed; the glyph is inside the 80 % safe circle.
    save(render(FULL, 192), web / "icons" / "Icon-maskable-192.png")
    save(render(FULL, 512), web / "icons" / "Icon-maskable-512.png")
    save(rounded(render(FULL, 64)), web / "favicon.png")

    sizes = [16, 24, 32, 48, 64, 128, 256]
    ico = rounded(render(FULL, 256))
    ico.save(
        APP / "windows" / "runner" / "resources" / "app_icon.ico",
        sizes=[(s, s) for s in sizes],
    )
    print("icons written")


if __name__ == "__main__":
    main()
